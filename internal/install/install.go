type Options struct {
	Harness, Scope, Dir, Guard, Record, DB, Version, Binary, WrapDB string
	Only, Except, FailOpen                                          []string
	Timeout                                                         int
	NoFailClosed, DryRun, List, Uninstall, Restore                  bool
	Out                                                             io.Writer
}
type handler struct {
	Group, Index, Position int
	Path, Command, Raw     string
	Matcher                *string
}

func (h handler) matcher() string {
	if h.Matcher == nil {
		return ""
	}
	return *h.Matcher
}
func (h handler) result() gjson.Result { return gjson.Parse(h.Raw) }
func codexHome() string {
	if p := os.Getenv("CODEX_HOME"); p != "" {
		if real, err := filepath.EvalSymlinks(p); err == nil {
			return real
		}
		return p
	}
	home, _ := os.UserHomeDir()
	p := filepath.Join(home, ".codex")
	if real, err := filepath.EvalSymlinks(p); err == nil {
		return real
	}
	return p
}
func targets(o Options) (settings, config string, err error) {
	if o.Harness != "claude" && o.Harness != "codex" {
		return "", "", fmt.Errorf("harness must be claude or codex")
	}
	if o.Scope != "user" && o.Scope != "project" && o.Scope != "local" {
		return "", "", fmt.Errorf("scope must be user, project or local")
	}
	if o.Harness == "codex" && o.Scope == "local" {
		return "", "", fmt.Errorf("codex has no local scope")
	}
	dir, err := filepath.Abs(o.Dir)
	if err != nil {
		return "", "", err
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", "", err
	}
	if o.Harness == "claude" {
		base := filepath.Join(dir, ".claude")
		if o.Scope == "user" {
			base = filepath.Join(home, ".claude")
		}
		file := "settings.json"
		if o.Scope == "local" {
			file = "settings.local.json"
		}
		return filepath.Join(base, file), "", nil
	}
	base := filepath.Join(dir, ".codex")
	if o.Scope == "user" {
		base = codexHome()
	}
	return filepath.Join(base, "hooks.json"), filepath.Join(codexHome(), "config.toml"), nil
}
func discover(raw []byte) ([]handler, error) {
	if !gjson.ValidBytes(raw) || !utf8.Valid(raw) {
		return nil, fmt.Errorf("invalid settings JSON")
	}
	root := gjson.ParseBytes(raw)
	if !root.IsObject() {
		return nil, fmt.Errorf("settings JSON must be an object")
	}
	groups := root.Get("hooks.PreToolUse")
	if !groups.Exists() {
		return nil, nil
	}
	if !groups.IsArray() {
		return nil, fmt.Errorf("hooks.PreToolUse must be an array")
	}
	out := []handler{}
	position := 0
	for gi, group := range groups.Array() {
		if !group.IsObject() {
			return nil, fmt.Errorf("PreToolUse group %d must be an object", gi)
		}
		hs := group.Get("hooks")
		if !hs.IsArray() {
			return nil, fmt.Errorf("PreToolUse group %d hooks must be an array", gi)
		}
		for hi, h := range hs.Array() {
			position++
			if h.Get("type").String() != "command" {
				continue
			}
			if h.Get("command").Type != gjson.String {
				return nil, fmt.Errorf("handler %d command must be a string", position)
			}
			path := fmt.Sprintf("hooks.PreToolUse.%d.hooks.%d", gi, hi)
			out = append(out, handler{gi, hi, position, path, h.Get("command").String(), h.Raw, matcherPointer(group)})
		}
	}
	return out, nil
}
func match(text string, filters []string) bool {
	for _, s := range filters {
		if strings.Contains(text, s) {
			return true
		}
	}
	return false
}
func selected(h handler, o Options) bool {
	return (len(o.Only) == 0 || match(h.Command, o.Only)) && !match(h.Command, o.Except)
}
func wrappedArgs(h handler, harness string) ([]string, bool) {
	r := h.result()
	var args []string
	if harness == "claude" && r.Get("args").Exists() {
		args = []string{r.Get("command").String()}
		for _, a := range r.Get("args").Array() {
			if a.Type != gjson.String {
				return nil, false
			}
			args = append(args, a.String())
		}
	} else {
		words, err := guard.Words(h.Command)
		if err != nil || words == nil {
			return nil, false
		}
		// Recognition never expands environment variables or executes substitutions.
		for _, w := range words {
			s, err := unquoteWord(w)
			if err != nil {
				return nil, false
			}
			args = append(args, s)
		}
	}
	if len(args) < 2 || filepath.Base(args[0]) != "blotter" || args[1] != "wrap" {
		return nil, false
	}
	return args, true
}
func unquoteWord(s string) (string, error) {
	// Shell quoting generated by ShellJoin contains no expansions. Parse it with
	// the shell library while isolating it from the user's environment.
	f, err := syntax.NewParser().Parse(strings.NewReader(s), "")
	if err != nil {
		return "", err
	}
	if len(f.Stmts) != 1 {
		return "", fmt.Errorf("invalid word")
	}
	c, ok := f.Stmts[0].Cmd.(*syntax.CallExpr)
	if !ok || len(c.Args) != 1 {
		return "", fmt.Errorf("invalid word")
	}
	return expand.Literal(&expand.Config{Env: expand.ListEnviron()}, c.Args[0])
}
func BinaryPath(path string) (string, error) {
	var err error
	if path == "" {
		path, err = os.Executable()
		if err != nil {
			return "", err
		}
	}
	path, err = filepath.EvalSymlinks(path)
	if err != nil {
		return "", err
	}
	parts := strings.Split(filepath.ToSlash(path), "/")
	for i, p := range parts {
		if p == "Cellar" && i+3 < len(parts) && parts[i+1] == "blotter" {
			return filepath.FromSlash(strings.Join(parts[:i], "/") + "/opt/blotter/bin/blotter"), nil
		}
	}
	return filepath.Abs(path)
}
func put(raw []byte, path string, value any) ([]byte, error) { return sjson.SetBytes(raw, path, value) }
func putRaw(raw []byte, path, value string) ([]byte, error) {
	// SetRaw's default path compacts the replacement. Optimistic replacement
	// preserves the saved object's internal formatting verbatim.
	return sjson.SetRawBytesOptions(raw, path, []byte(value), &sjson.Options{Optimistic: true})
}
func prepareWrapped(h handler, o Options, binary, name string) (string, bool, error) {
	raw := []byte(h.Raw)
	result := h.result()
	args := []string{"wrap", "--harness", o.Harness, "--guard", name}
	if o.WrapDB != "" {
		args = append(args, "--db", o.WrapDB)
	}
	if o.Record != "full" {
		args = append(args, "--record", o.Record)
	}
	var words []string
	var err error
	shell := false
	if o.Harness == "claude" && result.Get("args").Exists() {
		if !result.Get("args").IsArray() {
			return "", false, fmt.Errorf("args must be an array")
		}
		words = []string{h.Command}
		for _, a := range result.Get("args").Array() {
			if a.Type != gjson.String {
				return "", false, fmt.Errorf("args must contain strings")
			}
			words = append(words, a.String())
		}
		args = append(args, "--")
		args = append(args, words...)
	} else {
		words, err = guard.Words(h.Command)
		if err != nil {
			return "", false, fmt.Errorf("handler %d: %w", h.Position, err)
		}
		if words == nil {
			shell = true
			args = append(args, "--sh", h.Command)
		} else {
			args = append(args, "--shell-words", "--")
			args = append(args, words...)
		}
	}
	if o.Harness == "claude" {
		raw, err = put(raw, "command", binary)
		if err == nil {
			raw, err = put(raw, "args", args)
		}
		if err == nil && !o.NoFailClosed && !match(h.Command, o.FailOpen) {
			raw, err = put(raw, "onFailure", "block")
		}
		if err == nil && match(h.Command, o.FailOpen) {
			raw, err = sjson.DeleteBytes(raw, "onFailure")
		}
	} else {
		raw, err = put(raw, "command", guard.ShellJoin(append([]string{binary}, args...)))
	}
	if err == nil && o.Timeout > 0 {
		raw, err = put(raw, "timeout", o.Timeout)
	}
	return string(raw), shell, err
}
func Apply(o Options) error {
	if o.Out == nil {
		o.Out = io.Discard
	}
	report := &reportWriter{Writer: o.Out}
	o.Out = report
	if o.Dir == "" {
		o.Dir = "."
	}
	if o.Scope == "" {
		o.Scope = "user"
	}
	if o.Record == "" {
		o.Record = "full"
	}
	if o.DB == "" {
		o.DB = store.DBPath("")
	}
	var pathErr error
	o.DB, pathErr = filepath.Abs(o.DB)
	if pathErr != nil {
		return pathErr
	}
	if o.Record != "full" && o.Record != "hash" {
		return fmt.Errorf("--record must be full or hash")
	}
	if o.Timeout < 0 {
		return fmt.Errorf("--timeout must be positive")
	}
	if o.Guard != "" && len(o.Only) != 1 {
		return fmt.Errorf("--guard requires one --only selector matching one handler")
	}
	target, configPath, err := targets(o)
	if err != nil {
		return err
	}
	if !o.DryRun && !o.List {
		lock, err := lockInstall()
		if err != nil {
			return err
		}
		defer unlock(lock)
		if err = recoverPending(); err != nil {
			return fmt.Errorf("interrupted install recovery: %w", err)
		}
	}
	settings, err := readChange(target)
	if err != nil {
		return err
	}
	if !settings.Exists {
		_, err = fmt.Fprintf(o.Out, "unchanged %s (no hooks file)\n", target)
		return err
	}
	handlers, err := discover(settings.Before)
	if err != nil {
		return fmt.Errorf("%s: %w", target, err)
	}
	var config change
	if configPath != "" {
		config, err = readChange(configPath)
		if err != nil {
			return err
		}
		if err = detectInline(config.Before); err != nil {
			return err
		}
		if o.Scope == "project" {
			projectConfig, err := readChange(filepath.Join(filepath.Dir(target), "config.toml"))
			if err != nil {
				return err
			}
			if err = detectInline(projectConfig.Before); err != nil {
				return err
			}
		}
	}
	if o.List {
		for _, h := range handlers {
			_, wrapped := wrappedArgs(h, o.Harness)
			_, err = fmt.Fprintf(o.Out, "%d matcher=%q wrapped=%t command=%s\n", h.Position, h.matcher(), wrapped, h.Command)
			if err != nil {
				return err
			}
		}
		return nil
	}
	all, err := readManifests(o.DB)
	if err != nil {
		return err
	}
	if o.Uninstall {
		return uninstall(o, settings, config, handlers, all)
	}
	binary, err := BinaryPath(o.Binary)
	if err != nil {
		return err
	}
	if o.Guard != "" {
		count := 0
		for _, h := range handlers {
			if selected(h, o) {
				count++
			}
		}
		if count != 1 {
			return fmt.Errorf("--guard requires exactly one matching handler, found %d", count)
		}
	}
	used := map[string]bool{}
	for _, m := range all {
		if m.Target == settings.Path {
			used[m.Guard] = true
		}
	}
	for _, h := range handlers {
		if args, ok := wrappedArgs(h, o.Harness); ok {
			used[argValue(args, "--guard")] = true
		}
	}
	changed := false
	for _, h := range handlers {
		if !selected(h, o) {
			continue
		}
		if args, ok := wrappedArgs(h, o.Harness); ok {
			idx := manifestIndex(all, settings.Path, h)
			if idx < 0 {
				_, _ = fmt.Fprintf(o.Out, "orphaned wrapped handler %d: no manifest; left unchanged\n", h.Position)
				continue
			}
			if all[idx].Wrapped != h.Raw {
				_, _ = fmt.Fprintf(o.Out, "edited wrapped handler %s: left unchanged\n", all[idx].Guard)
				continue
			}
			if args[0] == binary {
				_, _ = fmt.Fprintf(o.Out, "already wrapped %s\n", all[idx].Guard)
				continue
			}
			args[0] = binary
			next := []byte(h.Raw)
			if o.Harness == "claude" {
				next, err = put(next, "command", binary)
			} else {
				next, err = put(next, "command", guard.ShellJoin(args))
			}
			if err != nil {
				return err
			}
			if o.Harness == "codex" {
				oldHash, e := CodexHash(h.Matcher, h.Raw)
				if e != nil {
					return e
				}
				newHash, e := CodexHash(h.Matcher, string(next))
				if e != nil {
					return e
				}
				current, _, e := trustState(config.After, all[idx].TrustKey)
				if e != nil {
					return e
				}
				if current == oldHash {
					config.After, err = patchTrust(config.After, all[idx].TrustKey, newHash)
					if err != nil {
						return err
					}
				}
			}
			settings.After, err = putRaw(settings.After, h.Path, string(next))
			if err != nil {
				return err
			}
			all[idx].Wrapped = string(next)
			changed = true
			_, _ = fmt.Fprintf(o.Out, "updated blotter path for %s\n", all[idx].Guard)
			continue
		}
		var words []string
		if o.Harness == "claude" && h.result().Get("args").Exists() {
			words = []string{h.Command}
			for _, a := range h.result().Get("args").Array() {
				words = append(words, a.String())
			}
		} else {
			words, err = guard.Words(h.Command)
			if err != nil {
				return fmt.Errorf("handler %d: %w", h.Position, err)
			}
		}
		name := o.Guard
		if name == "" {
			name = guard.Name(words, h.matcher(), h.Position)
		}
		base := name
		for n := 2; used[name]; n++ {
			name = fmt.Sprintf("%s-%d", base, n)
		}
		used[name] = true
		next, shell, err := prepareWrapped(h, o, binary, name)
		if err != nil {
			return err
		}
		m := Manifest{Harness: o.Harness, Scope: o.Scope, Target: settings.Path, Event: "PreToolUse", GroupIndex: h.Group, HandlerIndex: h.Index, Guard: name, Original: h.Raw, Wrapped: next, InstalledAt: store.Timestamp(time.Now()), Version: o.Version, FailOpen: o.NoFailClosed || match(h.Command, o.FailOpen)}
		m.SourceTarget, _ = filepath.Abs(target)
		if o.Harness == "codex" {
			lexical, err := filepath.Abs(target)
			if err != nil {
				return err
			}
			m.TrustKey = trustKey(lexical, h)
			oldHash, e := CodexHash(h.Matcher, h.Raw)
			if e != nil {
				return e
			}
			newHash, e := CodexHash(h.Matcher, next)
			if e != nil {
				return e
			}
			current, _, e := trustState(config.After, m.TrustKey)
			if e != nil {
				return e
			}
			if t, ok, e := findTrust(config.After, m.TrustKey); e != nil {
				return e
			} else if ok {
				prior := string(config.After[t.Start:t.End])
				m.PriorTrust = &prior
			}
			if current == oldHash {
				config.After, err = patchTrust(config.After, m.TrustKey, newHash)
				if err != nil {
					return err
				}
			} else {
				_, _ = fmt.Fprintf(o.Out, "%s: approve this wrapped hook in Codex /hooks (trust was not granted)\n", name)
			}
		}
		settings.After, err = putRaw(settings.After, h.Path, next)
		if err != nil {
			return err
		}
		all = append(all, m)
		changed = true
		_, _ = fmt.Fprintf(o.Out, "wrapped %s (handler %d, matcher %q)\n", name, h.Position, h.matcher())
		if shell {
			_, _ = fmt.Fprintf(o.Out, "warning: %s uses /bin/sh; missing inner programs cannot be distinguished from exit 127\n", name)
		}
	}
	changes := []change{settings}
	if configPath != "" {
		changes = append(changes, config)
	}
	if changed && o.Harness == "codex" {
		_, _ = fmt.Fprintln(o.Out, "warning: Codex fails open if blotter is missing or crashes; shell launch failures also fail open")
	}
	if changed && o.Harness == "claude" {
		_, _ = fmt.Fprintln(o.Out, "Claude onFailure=block stops tool calls when a wrapped guard breaks or times out, except explicit fail-open handlers")
		if err := claudeVersion(); err != nil {
			_, _ = fmt.Fprintf(o.Out, "warning: %v\n", err)
		}
	}
	for _, c := range changes {
		if err = printDiff(o.Out, c); err != nil {
			return err
		}
	}
	if o.DryRun || !changed {
		return nil
	}
	return commitChanges(changes, all, o)
}
func manifestIndex(all []Manifest, target string, h handler) int {
	for i, m := range all {
		if m.Target == target && m.Event == "PreToolUse" && m.GroupIndex == h.Group && m.HandlerIndex == h.Index {
			return i
		}
	}
	return -1
}
func splitWrappedArgs(args []string) (flags, command []string) {
	for i := 2; i < len(args); i++ {
		if args[i] == "--" {
			return args[:i], args[i+1:]
		}
		switch args[i] {
		case "--guard", "--harness", "--db", "--record", "--log", "--sh":
			i++
		}
	}
	return args, nil
}
func argValue(args []string, key string) string {
	flags, _ := splitWrappedArgs(args)
	value := ""
	for i := 2; i < len(flags); i++ {
		a := flags[i]
		if a == key {
			if key == "--shell-words" {
				value = "true"
			} else if i+1 < len(flags) {
				value = flags[i+1]
			}
		}
		if strings.HasPrefix(a, key+"=") {
			value = strings.TrimPrefix(a, key+"=")
		}
		switch a {
		case "--guard", "--harness", "--db", "--record", "--log", "--sh":
			i++
		}
	}
	return value
}
func hasShellWords(args []string) bool {
	return argValue(args, "--shell-words") == "true"
}
func uninstall(o Options, settings, config change, handlers []handler, all []Manifest) error {
	if o.Restore {
		var err error
		settings.After, err = newestBackup(settings.Path)
		if err != nil {
			return err
		}
		if _, err = discover(settings.After); err != nil {
			return fmt.Errorf("invalid backup: %w", err)
		}
	}
	remove := map[int]bool{}
	for i, m := range all {
		if m.Target != settings.Path || m.Harness != o.Harness || (len(o.Only) > 0 && !match(m.Guard, o.Only)) {
			continue
		}
		path := fmt.Sprintf("hooks.PreToolUse.%d.hooks.%d", m.GroupIndex, m.HandlerIndex)
		if !o.Restore && gjson.GetBytes(settings.Before, path).Raw != m.Wrapped {
			_, _ = fmt.Fprintf(o.Out, "edited or missing %s: left unchanged\n", m.Guard)
			continue
		}
		var err error
		if !o.Restore {
			settings.After, err = putRaw(settings.After, path, m.Original)
			if err != nil {
				return err
			}
		}
		if o.Harness == "codex" && m.TrustKey != "" {
			var matcher *string
			for _, h := range handlers {
				if h.Group == m.GroupIndex && h.Index == m.HandlerIndex {
					matcher = h.Matcher
					break
				}
			}
			expected, e := CodexHash(matcher, m.Wrapped)
			if e != nil {
				return e
			}
			current, _, e := trustState(config.After, m.TrustKey)
			if e != nil {
				return e
			}
			if current == expected {
				config.After, err = restoreTrust(config.After, m.TrustKey, m.PriorTrust)
				if err != nil {
					return err
				}
			} else {
				_, _ = fmt.Fprintf(o.Out, "trust state for %s changed or was not carried: left unchanged\n", m.Guard)
			}
		}
		remove[i] = true
		_, _ = fmt.Fprintf(o.Out, "restored %s\n", m.Guard)
	}
	for _, h := range handlers {
		if _, ok := wrappedArgs(h, o.Harness); ok && manifestIndex(all, settings.Path, h) < 0 {
			_, _ = fmt.Fprintf(o.Out, "orphaned wrapped handler %d: left unchanged\n", h.Position)
		}
	}
	next := []Manifest{}
	for i, m := range all {
		if !remove[i] {
			next = append(next, m)
		}
	}
	changes := []change{settings}
	if config.Path != "" {
		changes = append(changes, config)
	}
	for _, c := range changes {
		if err := printDiff(o.Out, c); err != nil {
			return err
		}
	}
	if o.DryRun {
		return nil
	}
	return commitChanges(changes, next, o)
}

var versionRE = regexp.MustCompile(`(\d+)\.(\d+)\.(\d+)`)

func claudeVersion() error {
	if os.Geteuid() == 0 {
		return nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "claude", "--version").Output()
	if err != nil {
		return fmt.Errorf("could not verify Claude version: %w", err)
	}
	m := versionRE.FindStringSubmatch(string(out))
	if len(m) != 4 {
		return fmt.Errorf("unrecognized Claude version")
	}
	v := []int{}
	for _, p := range m[1:] {
		n, _ := strconv.Atoi(p)
		v = append(v, n)
	}
	if v[0] < 2 || (v[0] == 2 && (v[1] < 1 || (v[1] == 1 && v[2] < 295))) {
		return fmt.Errorf("claude %s predates 2.1.295; onFailure block is unsupported", m[0])
	}
	return nil
}
